// Generates the TypeScript modules of @elabora/format from its JSON Schemas:
// - src/types.generated.ts: one type per schema and per $defs entry, a type for each array item or
//   map value that is an object, and the union of built-in blocks (from the dispatch in block.schema.json);
// - src/schemas.generated.ts: every schema imported as a JSON module, so the package reads no file.
// Run `npm run gen` after changing a schema; test/unit/format.test.ts fails while the files are stale.
import fs from 'node:fs';
import path from 'node:path';
import type { JsonSchema } from '@elabora/format/json-schema';

// The format version the packages implement: its schemas are in packages/format/schemas/<version>/.
// The version of the schemas (their folder and $id): additive changes to a published version are
// published as its next patch (D64: 0.1.1, then 0.1.2 for continuity, D65). The format a course declares stays elabora/<FORMAT_VERSION>.
const SCHEMA_VERSION = '0.1.2';
const FORMAT_VERSION = '0.1';

const ROOT = path.resolve(import.meta.dirname, '..');
const SCHEMA_DIR = `packages/format/schemas/${SCHEMA_VERSION}`;
const TYPES_FILE = 'packages/format/src/types.generated.ts';
const SCHEMAS_FILE = 'packages/format/src/schemas.generated.ts';
const HEADER = `// Generated by scripts/gen-format.ts from ${SCHEMA_DIR}: do not edit. Run \`npm run gen\`.\n`;

// Type names that are not the PascalCase of the schema file (blocks/<type> gives <Type>Props) or of
// the $defs entry.
const TYPE_NAMES: Record<string, string> = {
  component: 'ComponentManifest',
  'defs#date': 'CalendarDate', // Date would shadow the global Date
  'plan#item': 'PlanItem',
  'plan#question': 'PlanQuestion',
  'plan-version#note': 'PlanNote'
};
// An object in an array or a map gets a type named after its place: the owner's name (or this shorter
// prefix), then the property in the singular (CourseSection, QuizOption, ObjectEvent).
const PREFIXES: Record<string, string> = { ComponentManifest: 'Component', ObjectManifest: 'Object', ObjectTests: 'Object' };
const PLACE_NAMES: Record<string, string> = { ObjectObject: 'ObjectPart', PlanItemLockedText: 'LockedText', PlanDecided: 'PlanDecision', PlanVersionSend: 'PlanSend' };
// Order of the schemas in types.generated.ts; others follow by name.
const ORDER = ['defs', 'course', 'plan', 'plan-version', 'plan-notes', 'screen', 'block', 'blocks/', 'layouts/', 'event', 'component', 'object-manifest', 'object-tests', 'diagnostic', 'lms-profile'];

// Keywords the generator understands. Any other keyword (except x-* annotations) stops it, rather
// than producing a type that silently accepts too much.
const KEYWORDS = new Set([
  '$schema', '$id', '$ref', '$defs', '$comment', 'title', 'description', 'default', 'examples',
  'type', 'enum', 'const', 'properties', 'required', 'additionalProperties', 'patternProperties', 'propertyNames',
  'minProperties', 'maxProperties', 'items', 'prefixItems', 'minItems', 'maxItems', 'uniqueItems',
  'minLength', 'maxLength', 'pattern', 'format', 'minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum', 'multipleOf',
  'allOf', 'anyOf', 'oneOf', 'not', 'if', 'then', 'else', 'unevaluatedProperties'
]);

interface SchemaFile { name: string; file: string; id: string; schema: JsonSchema }

type Literal = string | number | boolean | null;
type TypeNode =
  | { kind: 'name'; name: string }
  | { kind: 'literal'; value: Literal }
  | { kind: 'union'; members: TypeNode[] }
  | { kind: 'intersection'; members: TypeNode[] }
  | { kind: 'array'; element: TypeNode }
  | { kind: 'tuple'; elements: TypeNode[]; rest: TypeNode | null }
  | { kind: 'object'; members: Member[]; index: Index | null };
interface Member { key: string; optional: boolean; type: TypeNode; doc: string[] }
interface Index { type: TypeNode; doc: string[] }
// key: what the type is made from (a schema, a $defs entry…); section: the schema file it belongs to.
interface Declaration { name: string; key: string; section: string; doc: string[]; type: TypeNode }
// Where a subschema sits: its file (for $ref) and the name a type declared there would take.
interface Place { file: SchemaFile; name: string }
// allOf entries of the form if { D: const V } then { P: $ref R }: the type of P depends on D.
interface Dispatch { discriminator: string; property: string; variants: { value: string; ref: string }[] }

const named = (name: string): TypeNode => ({ kind: 'name', name });
const UNKNOWN = named('unknown');
const NEVER = named('never');

export function generateFormatFiles(): { path: string; content: string }[] {
  const files = loadSchemas();
  return [{ path: TYPES_FILE, content: typesModule(files) }, { path: SCHEMAS_FILE, content: schemasModule(files) }];
}

function loadSchemas(): SchemaFile[] {
  const list = (dir: string, base: string): string[] => fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })
    .flatMap((entry) => entry.isDirectory() ? list(`${dir}/${entry.name}`, `${base}${entry.name}/`) : entry.name.endsWith('.schema.json') ? [`${base}${entry.name}`] : []);
  return list(SCHEMA_DIR, '').sort(compare).map((file) => {
    const schema = JSON.parse(fs.readFileSync(path.join(ROOT, SCHEMA_DIR, file), 'utf8')) as JsonSchema;
    if (typeof schema.$id !== 'string') throw new Error(`${file}: no $id`);
    return { name: file.replace(/\.schema\.json$/, ''), file, id: schema.$id, schema };
  });
}

// ---------------------------------------------------------------------------------------------
// types.generated.ts

function typesModule(files: SchemaFile[]): string {
  const byId = new Map(files.map((f) => [f.id, f]));
  const declarations = new Map<string, Declaration>();
  let section = '';

  const rootName = (file: SchemaFile) => TYPE_NAMES[file.name] ?? (file.name.startsWith('blocks/') ? `${pascal(file.name.slice('blocks/'.length))}Props` : file.name.startsWith('layouts/') ? `${pascal(file.name.slice('layouts/'.length))}LayoutProps` : pascal(file.name));
  const defName = (file: SchemaFile, def: string) => TYPE_NAMES[`${file.name}#${def}`] ?? pascal(def);

  // The same name made from something else is a clash.
  const declare = (name: string, key: string, doc: string[], type: () => TypeNode) => {
    const existing = declarations.get(name);
    if (existing) {
      if (existing.key === key) return;
      throw new Error(`Two different types would be named ${name}: add a name to TYPE_NAMES or PLACE_NAMES in scripts/gen-format.ts`);
    }
    // Reserve the place first, so a type comes before the types of its items.
    const declaration: Declaration = { name, key, section, doc, type: UNKNOWN };
    declarations.set(name, declaration);
    declaration.type = type();
  };

  const refName = (ref: string, from: SchemaFile): string => {
    const url = new URL(ref, from.id);
    const target = byId.get(url.href.replace(/#.*$/, ''));
    if (!target) throw new Error(`${from.file}: $ref ${ref} points outside the format`);
    if (url.hash === '' || url.hash === '#') {
      if (isContainer(target.schema)) throw new Error(`${from.file}: $ref ${ref} points to a schema without a type`);
      return rootName(target);
    }
    const def = /^#\/\$defs\/([^/]+)$/.exec(url.hash)?.[1];
    if (!def || target.schema.$defs?.[decodeURIComponent(def)] === undefined) throw new Error(`${from.file}: unsupported $ref ${ref}`);
    return defName(target, decodeURIComponent(def));
  };

  // Objects declared as their own type, by their schema text: the same object written twice in the
  // schemas gets one type.
  const hoisted = new Map<string, string>();
  const hoist = (schema: JsonSchema, place: Place): TypeNode => {
    const key = JSON.stringify(schema);
    let name = hoisted.get(key);
    if (!name) {
      const declaredName = PLACE_NAMES[place.name] ?? place.name;
      hoisted.set(key, declaredName);
      declare(declaredName, key, docOf(schema), () => convert(schema, { file: place.file, name: declaredName }));
      name = declaredName;
    }
    return named(name);
  };
  // An object with properties in an array or a map is declared as its own type, and so is an
  // extension of a definition ($ref with properties of its own: a narration line is a voice line).
  const placed = (schema: JsonSchema | boolean, place: Place): TypeNode =>
    typeof schema === 'object' && (isPlainObject(schema) || isExtension(schema)) ? hoist(schema, place) : convert(schema, place);
  // A property's object stays inline, unless the same object is written elsewhere too.
  const repeated = repeatedObjects(files);
  // Definitions that other schemas extend and close ($ref next to unevaluatedProperties: false).
  const extended = extendedDefinitions(files, byId);
  const property = (schema: JsonSchema | boolean, place: Place): TypeNode =>
    typeof schema === 'object' && isPlainObject(schema) && repeated.has(JSON.stringify(schema)) ? hoist(schema, place) : convert(schema, place);

  const convert = (schema: JsonSchema | boolean, place: Place): TypeNode => {
    if (schema === true) return UNKNOWN;
    if (schema === false) return NEVER;
    for (const keyword of Object.keys(schema)) {
      if (!keyword.startsWith('x-') && !KEYWORDS.has(keyword)) throw new Error(`${place.file.file}: keyword ${keyword} (at ${place.name}) is not supported by scripts/gen-format.ts`);
    }
    let type: TypeNode;
    if (schema.$ref !== undefined) type = named(refName(schema.$ref, place.file));
    else if ('const' in schema) type = literal(schema.const, place);
    else if (schema.enum) type = union(schema.enum.map((value) => literal(value, place)));
    else if (schema.anyOf || schema.oneOf) type = union([...schema.anyOf ?? [], ...schema.oneOf ?? []].map((s) => convert(s, place)));
    else type = structure(schema, place);
    const parts = [type];
    // Properties or items next to a $ref or a combination narrow it.
    const combined = schema.$ref !== undefined || schema.anyOf !== undefined || schema.oneOf !== undefined;
    if (combined && ['properties', 'additionalProperties', 'patternProperties', 'items', 'prefixItems'].some((k) => k in schema)) parts.push(structure(schema, place));
    // if/then/else only add constraints to the base type; allOf entries made of them are skipped.
    for (const entry of schema.allOf ?? []) if (!isConditional(entry)) parts.push(convert(entry, place));
    return intersection(parts);
  };

  const structure = (schema: JsonSchema, place: Place): TypeNode => {
    const types = schema.type === undefined ? impliedTypes(schema) : Array.isArray(schema.type) ? schema.type : [schema.type];
    if (!types.length) return UNKNOWN;
    return union(types.map((type): TypeNode => {
      switch (type) {
        case 'string': return named('string');
        case 'number': case 'integer': return named('number');
        case 'boolean': return named('boolean');
        case 'null': return named('null');
        case 'array': return arrayType(schema, place);
        case 'object': return objectType(schema, place);
        default: throw new Error(`${place.file.file}: unknown type ${type} (at ${place.name})`);
      }
    }));
  };

  const arrayType = (schema: JsonSchema, place: Place): TypeNode => {
    const itemPlace = { file: place.file, name: singular(place.name) };
    if (schema.prefixItems) {
      const elements = schema.prefixItems.map((s) => placed(s, itemPlace));
      const closed = schema.items === false || (schema.items === undefined && schema.maxItems === elements.length);
      return { kind: 'tuple', elements, rest: closed ? null : schema.items === undefined ? UNKNOWN : placed(schema.items, itemPlace) };
    }
    const element = schema.items === undefined ? UNKNOWN : placed(schema.items, itemPlace);
    // A small fixed length reads better as a tuple: [width, height].
    const length = schema.minItems;
    if (length !== undefined && length === schema.maxItems && length >= 1 && length <= 4) return { kind: 'tuple', elements: Array.from({ length }, () => element), rest: null };
    return { kind: 'array', element };
  };

  const objectType = (schema: JsonSchema, place: Place): TypeNode => {
    const required = new Set(schema.required ?? []);
    const properties = schema.properties ?? {};
    const members: Member[] = Object.entries(properties).map(([key, sub]) => ({
      key, optional: !required.has(key), type: property(sub, { file: place.file, name: place.name + pascal(key) }), doc: docOf(sub)
    }));
    for (const key of required) if (!(key in properties)) members.push({ key, optional: false, type: UNKNOWN, doc: [] });
    const valuePlace = { file: place.file, name: singular(place.name) };
    const values = Object.values(schema.patternProperties ?? {}).map((s) => placed(s, valuePlace));
    // unevaluatedProperties false closes an extension as additionalProperties false closes an object;
    // a definition that extensions close stays open for validation, but its type is closed.
    const additional = schema.additionalProperties ?? (schema.unevaluatedProperties === false || extended.has(schema) ? false : undefined);
    if (additional !== false) values.push(additional === undefined || additional === true ? UNKNOWN : placed(additional, valuePlace));
    if (!values.length) return { kind: 'object', members, index: null };
    // The index signature must accept every declared property too.
    let indexType = union(values);
    if (members.length && indexType !== UNKNOWN) indexType = UNKNOWN;
    return { kind: 'object', members, index: { type: indexType, doc: typeof additional === 'object' ? docOf(additional) : [] } };
  };

  const emitDispatch = (name: string, dispatch: Dispatch, file: SchemaFile) => {
    const { discriminator, property, variants } = dispatch;
    const base = `Omit<${name}, '${discriminator}' | '${property}'>`;
    const variantName = (value: string) => `${pascal(value)}${name}`;
    declare(`Builtin${name}Type`, `dispatch ${name}`, [`A built-in value of ${name}.${discriminator}.`], () => union(variants.map((v) => literal(v.value, { file, name }))));
    declare(`Builtin${name}`, `dispatch ${name}`, [`A ${name} whose ${discriminator} is built in: its ${property} follow the schema of that ${discriminator}.`], () => union(variants.map((v) => named(variantName(v.value)))));
    for (const v of variants) {
      declare(variantName(v.value), `dispatch ${name} ${v.value}`, [], () => intersection([named(base), {
        kind: 'object', index: null,
        members: [
          { key: discriminator, optional: false, type: literal(v.value, { file, name }), doc: [] },
          { key: property, optional: false, type: named(refName(v.ref, file)), doc: [] }
        ]
      }]));
    }
  };

  for (const file of [...files].sort(byOrder)) {
    section = file.file;
    if (!isContainer(file.schema)) {
      const name = rootName(file);
      declare(name, file.file, rootDoc(file.schema, name), () => convert(file.schema, { file, name: PREFIXES[name] ?? name.replace(/Props$/, '') }));
      const dispatch = dispatchOf(file.schema);
      if (dispatch) emitDispatch(name, dispatch, file);
    }
    for (const [def, schema] of Object.entries(file.schema.$defs ?? {})) {
      const name = defName(file, def);
      declare(name, `${file.file}#${def}`, docOf(schema), () => convert(schema, { file, name: PREFIXES[name] ?? name }));
    }
  }

  let out = HEADER;
  let current = '';
  for (const d of declarations.values()) {
    if (d.section !== current) {
      current = d.section;
      out += `\n// ${current}\n`;
    }
    out += `\n${printDoc(d.doc, '')}export type ${d.name} =${printDeclaredType(d.type)};\n`;
  }
  return out;
}

const byOrder = (a: SchemaFile, b: SchemaFile) => {
  const rank = (f: SchemaFile) => {
    const i = ORDER.findIndex((o) => (o.endsWith('/') ? f.name.startsWith(o) : f.name === o));
    return i === -1 ? ORDER.length : i;
  };
  return rank(a) - rank(b) || compare(a.name, b.name);
};

// A schema that only holds $defs (defs.schema.json) has no type of its own.
const isContainer = (schema: JsonSchema) => !['type', 'properties', '$ref', 'enum', 'const', 'anyOf', 'oneOf', 'allOf', 'items'].some((k) => k in schema);

const isPlainObject = (schema: JsonSchema) => schema.$ref === undefined && schema.enum === undefined && !('const' in schema)
  && !schema.anyOf && !schema.oneOf && (schema.type === undefined || schema.type === 'object') && Object.keys(schema.properties ?? {}).length > 0;

// Object schemas written more than once in the format.
function repeatedObjects(files: SchemaFile[]): Set<string> {
  const counts = new Map<string, number>();
  const walk = (value: unknown) => {
    if (Array.isArray(value)) value.forEach(walk);
    else if (value && typeof value === 'object') {
      if (isPlainObject(value as JsonSchema)) {
        const key = JSON.stringify(value);
        counts.set(key, (counts.get(key) ?? 0) + 1);
      }
      Object.values(value).forEach(walk);
    }
  };
  files.forEach((f) => walk(f.schema));
  return new Set([...counts].filter(([, count]) => count > 1).map(([key]) => key));
}

const isExtension = (schema: JsonSchema) => schema.$ref !== undefined && Object.keys(schema.properties ?? {}).length > 0;

// The definitions closed where they are used: { "$ref": "…#/$defs/voiceLine", "properties": { … },
// "unevaluatedProperties": false }. They must stay open themselves (a definition that closed itself
// would refuse the properties its extensions add), so their type is closed here.
function extendedDefinitions(files: SchemaFile[], byId: ReadonlyMap<string, SchemaFile>): Set<JsonSchema> {
  const out = new Set<JsonSchema>();
  const walk = (value: unknown, file: SchemaFile) => {
    if (Array.isArray(value)) { value.forEach((item) => walk(item, file)); return; }
    if (!value || typeof value !== 'object') return;
    const schema = value as JsonSchema;
    if (typeof schema.$ref === 'string' && schema.unevaluatedProperties === false) {
      const url = new URL(schema.$ref, file.id);
      const target = byId.get(url.href.replace(/#.*$/, ''));
      const def = /^#\/\$defs\/([^/]+)$/.exec(url.hash)?.[1];
      const found = def ? target?.schema.$defs?.[decodeURIComponent(def)] : undefined;
      if (found && typeof found === 'object') {
        if (found.additionalProperties !== undefined || found.unevaluatedProperties !== undefined) throw new Error(`${file.file}: ${schema.$ref} is extended (unevaluatedProperties: false), so it must not close itself`);
        out.add(found);
      }
    }
    Object.values(value).forEach((item) => walk(item, file));
  };
  files.forEach((file) => walk(file.schema, file));
  return out;
}

const isConditional = (schema: JsonSchema | boolean) => typeof schema === 'object' && 'if' in schema
  && Object.keys(schema).every((k) => ['if', 'then', 'else', 'description', '$comment'].includes(k));

const impliedTypes = (schema: JsonSchema): string[] => ['properties', 'additionalProperties', 'patternProperties', 'propertyNames'].some((k) => k in schema)
  ? ['object'] : ['items', 'prefixItems'].some((k) => k in schema) ? ['array'] : [];

function dispatchOf(schema: JsonSchema): Dispatch | null {
  if (!schema.allOf?.length) return null;
  let discriminator: string | null = null;
  let property: string | null = null;
  const variants: Dispatch['variants'] = [];
  for (const entry of schema.allOf) {
    if (typeof entry !== 'object' || typeof entry.if !== 'object' || typeof entry.then !== 'object' || Object.keys(entry).length !== 2) return null;
    const tested = Object.entries(entry.if.properties ?? {});
    const set = Object.entries(entry.then.properties ?? {});
    if (tested.length !== 1 || set.length !== 1 || Object.keys(entry.then).length !== 1) return null;
    const [[d, test]] = tested;
    const [[p, target]] = set;
    if (typeof test !== 'object' || typeof test.const !== 'string' || typeof target !== 'object' || typeof target.$ref !== 'string' || Object.keys(target).length !== 1) return null;
    if ((discriminator ?? d) !== d || (property ?? p) !== p) return null;
    discriminator = d;
    property = p;
    variants.push({ value: test.const, ref: target.$ref });
  }
  return discriminator && property ? { discriminator, property, variants } : null;
}

function literal(value: unknown, place: Place): TypeNode {
  if (value !== null && !['string', 'number', 'boolean'].includes(typeof value)) throw new Error(`${place.file.file}: enum or const ${JSON.stringify(value)} (at ${place.name}) is not a scalar`);
  return { kind: 'literal', value: value as Literal };
}

function union(types: TypeNode[]): TypeNode {
  const flat = types.flatMap((t) => (t.kind === 'union' ? t.members : [t]));
  if (flat.includes(UNKNOWN)) return UNKNOWN;
  const unique = [...new Map(flat.filter((t) => t !== NEVER).map((t) => [printType(t, ''), t])).values()];
  // true | false reads boolean.
  const isBool = (t: TypeNode) => t.kind === 'literal' && typeof t.value === 'boolean';
  const both = unique.filter(isBool).length === 2;
  const members: TypeNode[] = [];
  for (const t of unique) {
    if (both && isBool(t)) {
      if (!members.some((m) => m.kind === 'name' && m.name === 'boolean')) members.push(named('boolean'));
    } else if (!(t.kind === 'name' && t.name === 'boolean' && members.some((m) => m.kind === 'name' && m.name === 'boolean'))) members.push(t);
  }
  if (!members.length) return NEVER;
  return members.length === 1 ? members[0] : { kind: 'union', members };
}

function intersection(types: TypeNode[]): TypeNode {
  const flat = types.flatMap((t) => (t.kind === 'intersection' ? t.members : [t]));
  if (flat.includes(NEVER)) return NEVER;
  const members = [...new Map(flat.filter((t) => t !== UNKNOWN).map((t) => [printType(t, ''), t])).values()];
  if (!members.length) return UNKNOWN;
  return members.length === 1 ? members[0] : { kind: 'intersection', members };
}

function rootDoc(schema: JsonSchema, name: string): string[] {
  const title = schema.title && schema.title.replace(/\W/g, '').toLowerCase() !== name.toLowerCase() ? [schema.title] : [];
  const description = docOf(schema);
  return title.length && description.length ? [...title, '', ...description] : [...title, ...description];
}

function docOf(schema: JsonSchema | boolean): string[] {
  if (typeof schema !== 'object') return [];
  const lines = schema.description ? schema.description.split('\n') : [];
  if (schema.default !== undefined) lines.push(`@default ${printValue(schema.default)}`);
  return lines;
}

// ---------------------------------------------------------------------------------------------
// Printing

function printDeclaredType(type: TypeNode): string {
  const text = printType(type, '');
  // A long union of names is easier to read one member per line.
  if (type.kind === 'union' && text.length > 100 && !text.includes('\n')) return `\n${type.members.map((m) => `  | ${printType(m, '  ')}`).join('\n')}`;
  return ` ${text}`;
}

function printType(type: TypeNode, indent: string): string {
  switch (type.kind) {
    case 'name': return type.name;
    case 'literal': return printValue(type.value);
    case 'union': return type.members.map((m) => (m.kind === 'intersection' ? `(${printType(m, indent)})` : printType(m, indent))).join(' | ');
    case 'intersection': return type.members.map((m) => (m.kind === 'union' ? `(${printType(m, indent)})` : printType(m, indent))).join(' & ');
    case 'array': {
      const element = printType(type.element, indent);
      return type.element.kind === 'union' || type.element.kind === 'intersection' ? `(${element})[]` : `${element}[]`;
    }
    case 'tuple': {
      const elements = type.elements.map((e) => printType(e, indent));
      if (type.rest) elements.push(`...${printType({ kind: 'array', element: type.rest }, indent)}`);
      return `[${elements.join(', ')}]`;
    }
    case 'object': {
      if (!type.members.length && !type.index) return '{}';
      if (!type.members.length && type.index && !type.index.doc.length) return `{ [key: string]: ${printType(type.index.type, indent)} }`;
      const inner = `${indent}  `;
      const lines = type.members.map((m) => `${printDoc(m.doc, inner)}${inner}${printKey(m.key)}${m.optional ? '?' : ''}: ${printType(m.type, inner)};`);
      if (type.index) lines.push(`${printDoc(type.index.doc, inner)}${inner}[key: string]: ${printType(type.index.type, inner)};`);
      return `{\n${lines.join('\n')}\n${indent}}`;
    }
  }
}

function printDoc(lines: string[], indent: string): string {
  if (!lines.length) return '';
  const safe = lines.map((l) => l.replace(/\*\//g, '*\\/'));
  if (safe.length === 1) return `${indent}/** ${safe[0]} */\n`;
  return `${indent}/**\n${safe.map((l) => `${indent} *${l ? ` ${l}` : ''}`).join('\n')}\n${indent} */\n`;
}

const printKey = (key: string) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : printValue(key));

function printValue(value: unknown): string {
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  return JSON.stringify(value);
}

