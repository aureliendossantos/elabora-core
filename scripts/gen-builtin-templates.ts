// Generates packages/core/src/components/builtin-templates.generated.ts from the built-in templates
// (packages/core/src/components/builtin/*.html), so the core gets them as data instead of reading
// files. Run it after editing a built-in template: pnpm run gen. A unit test checks it is current.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const BUILTIN_DIR = path.join(ROOT, 'packages/core/src/components/builtin');
export const OUTPUT = path.join(ROOT, 'packages/core/src/components/builtin-templates.generated.ts');

export function builtinTemplatesModule(): string {
  const names = fs.readdirSync(BUILTIN_DIR).filter((f) => f.endsWith('.html')).sort();
  const entries = names.map((f) => `  ${JSON.stringify(f.slice(0, -5))}: ${JSON.stringify(fs.readFileSync(path.join(BUILTIN_DIR, f), 'utf8'))}`);
  return `// Generated by scripts/gen-builtin-templates.ts from src/components/builtin/*.html: do not edit.
// Edit the template files, then run \`pnpm run gen\`.
export const BUILTIN_TEMPLATES: Readonly<Record<string, string>> = {
${entries.join(',\n')}
};
`;
}

if (import.meta.main) {
  fs.writeFileSync(OUTPUT, builtinTemplatesModule());
  console.log(path.relative(ROOT, OUTPUT));
}
