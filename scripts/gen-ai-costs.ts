// Generates packages/core/src/ai/cost-ledger.generated.ts from the ledger of what paid AI services
// charge (ai-costs/periods.json and ai-costs/measurements.jsonl, docs/decisions.md D36): the price
// periods and the averages the estimates are shipped with. Run it after adding a measurement or a
// period: npm run gen (npm run costs:record runs it). It refuses a ledger with problems (a measurement
// with no period…), and a unit test checks that the generated module is current.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { costAverages, ledgerProblems } from '@elabora/core/ai/costs';
import type { CostLedger, Measurement } from '@elabora/core/ai/costs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const LEDGER_DIR = path.join(ROOT, 'ai-costs');
export const PERIODS = path.join(LEDGER_DIR, 'periods.json');
export const MEASUREMENTS = path.join(LEDGER_DIR, 'measurements.jsonl');
export const OUTPUT = path.join(ROOT, 'packages/core/src/ai/cost-ledger.generated.ts');

export const readLedger = (file = PERIODS): CostLedger => JSON.parse(fs.readFileSync(file, 'utf8')) as CostLedger;

export function readMeasurements(file = MEASUREMENTS): Measurement[] {
  if (!fs.existsSync(file)) return [];
  return fs.readFileSync(file, 'utf8').split('\n').filter((line) => line.trim()).map((line, index) => {
    try { return JSON.parse(line) as Measurement; } catch { throw new Error(`${path.relative(ROOT, file)}:${index + 1} is not JSON`); }
  });
}

// A measurement as a line of the ledger, its fields always in this order.
export function measurementLine(m: Measurement): string {
  const { provider, model, kind, plan, date, settings, sent, billed, period, source, observed, note, ...rest } = m;
  return JSON.stringify({ provider, model, kind, plan, date, settings, sent, billed, period, source, ...(observed ? { observed } : {}), ...(note ? { note } : {}), ...rest });
}

export function aiCostsModule(ledger = readLedger(), measurements = readMeasurements()): string {
  const problems = ledgerProblems(ledger, measurements);
  if (problems.length) throw new Error(`The cost ledger has problems:\n  ${problems.join('\n  ')}`);
  const book = { providers: ledger.providers, periods: ledger.periods, averages: costAverages(ledger, measurements) };
  return `// Generated by scripts/gen-ai-costs.ts from ai-costs/periods.json and ai-costs/measurements.jsonl: do not
// edit. Add a measurement or a period there (ai-costs/README.md), then run \`npm run gen\`.
import type { CostBook } from './costs.ts';

export const COST_BOOK: CostBook = ${JSON.stringify(book, null, 2)};
`;
}

if (import.meta.main) {
  try {
    fs.writeFileSync(OUTPUT, aiCostsModule());
    console.log(`Wrote ${path.relative(ROOT, OUTPUT)}`);
  } catch (error) {
    console.error((error as Error).message);
    process.exit(1);
  }
}
