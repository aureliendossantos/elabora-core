// Generates packages/core/src/project/course-template.generated.ts from the template of a new course
// (packages/node/templates/course/) and its rules for agents with their revision
// (packages/node/templates/agents-revisions.json, D34), so that the core writes a new module's files
// without reading a disk (docs/decisions/D111.md). Run by pnpm run gen, after the rules' revision is
// recorded (scripts/gen-agent-rules.ts); a unit test checks it is current.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const COURSE = path.join(ROOT, 'packages/node/templates/course');
const HISTORY = path.join(ROOT, 'packages/node/templates/agents-revisions.json');
export const OUTPUT = path.join(ROOT, 'packages/core/src/project/course-template.generated.ts');
// The files a new course is made from, by their path in the template; AGENTS.md apart (the rules).
const FILES = ['course.json', 'plan.json', 'screens/intro.json', 'gitignore'];

export function courseTemplateModule(): string {
  const rules = fs.readFileSync(path.join(COURSE, 'AGENTS.md'), 'utf8');
  const sha = crypto.createHash('sha256').update(rules).digest('hex').slice(0, 16);
  const revisions = (JSON.parse(fs.readFileSync(HISTORY, 'utf8')) as { revisions: { revision: number; sha: string }[] }).revisions;
  const revision = revisions.find((entry) => entry.sha === sha)?.revision;
  if (revision === undefined) throw new Error('The rules for agents have no revision yet: run pnpm run gen');
  const entries = FILES.map((file) => `  ${JSON.stringify(file)}: ${JSON.stringify(fs.readFileSync(path.join(COURSE, file), 'utf8'))}`);
  return `// Generated by scripts/gen-course-template.ts from packages/node/templates/course/: do not edit.
// Edit the template's files, then run \`pnpm run gen\`.
export const COURSE_TEMPLATE: Readonly<Record<string, string>> = {
${entries.join(',\n')}
};

// The rules a course gives its agents (AGENTS.md between its markers, D34), their revision and fingerprint.
export const AGENT_RULES = { revision: ${revision}, sha: ${JSON.stringify(sha)}, text: ${JSON.stringify(rules)} } as const;
`;
}

if (import.meta.main) {
  fs.writeFileSync(OUTPUT, courseTemplateModule());
  console.log(path.relative(ROOT, OUTPUT));
}
